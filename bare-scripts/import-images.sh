#!/bin/bash

set -x

if [ -z "${IMAGE_REGISTRY}" ]; then
    echo "IMAGE_REGISTRY is not set"
    exit 1
fi

TARBALL=${1:-}
tar -zxvf $TARBALL

CMD="./crane"

$CMD push --allow-nondistributable-artifacts --insecure images/appscode-charts-<repo>-<tag>.tar $IMAGE_REGISTRY/appscode-charts/<repo>:<tag>
